"""CampusFlow command line.

    python manage.py check-db              test the database connection
    python manage.py init-db [--drop]      create tables from sql/schema.sql
    python manage.py seed [--drop] [--no-demo]   create tables + roles/permissions/users/workflows (+ demo requests)
    python manage.py export-sql            write sql/sample_data.sql from the current database
    python manage.py run                   start the development server
"""
import argparse
import os
import sys

from app import create_app
import db as database


def sql_literal(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"


def export_sql(app, path):
    tables = ["roles", "permissions", "role_permissions", "departments", "users", "request_types",
              "workflow_rules", "requests", "request_steps", "approval_history", "attachments",
              "notifications", "audit_logs"]
    db = database.connect(app)
    out = ["-- CampusFlow sample data (generated by python manage.py export-sql).",
           "-- Load AFTER sql/schema.sql:  mysql -u root -p campusflow < sql/sample_data.sql",
           "-- All demo accounts use the password documented in README.md.",
           "SET FOREIGN_KEY_CHECKS = 0;", ""]
    for t in tables:
        rows = db.query("SELECT * FROM %s ORDER BY 1" % t if t != "role_permissions"
                        else "SELECT * FROM role_permissions ORDER BY role_id, permission_id")
        if not rows:
            continue
        cols = list(rows[0].keys())
        out.append("-- %s" % t)
        for r in rows:
            out.append("INSERT INTO %s (%s) VALUES (%s);" % (t, ", ".join(cols), ", ".join(sql_literal(r[c]) for c in cols)))
        out.append("")
    out.append("SET FOREIGN_KEY_CHECKS = 1;")
    db.close()
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print("Wrote", path)


def check_db(app):
    cfg = app.config
    print("Backend :", cfg["DB_BACKEND"])
    if cfg["DB_BACKEND"] == "mysql":
        print("Server  : %s:%s  user=%s  database=%s" % (cfg["MYSQL_HOST"], cfg["MYSQL_PORT"], cfg["MYSQL_USER"], cfg["MYSQL_DB"]))
    try:
        import pymysql # noqa: F401
    except ImportError:
        if cfg["DB_BACKEND"] == "mysql":
            print("FAIL: PyMySQL is not installed. Run: pip install -r requirements.txt")
            return 1
    try:
        db = database.connect(app)
    except Exception as exc:                      # show a friendly, specific hint
        msg = str(exc)
        print("FAIL: cannot connect ->", msg)
        if "Access denied" in msg:
            print("Hint: wrong MYSQL_USER / MYSQL_PASSWORD in .env, or the user lacks rights on the database.")
        elif "Unknown database" in msg:
            print("Hint: create it first:  CREATE DATABASE campusflow CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;")
        elif "Can't connect" in msg or "refused" in msg or "timed out" in msg:
            print("Hint: MySQL is not running (start the MySQL80 service) or host/port in .env is wrong.")
        return 1
    print("OK: connected.")
    try:
        n = db.scalar("SELECT COUNT(*) FROM users")
        print("Tables present. users =", n, "(0 means run: python manage.py seed --drop)" if not n else "")
    except Exception:
        print("Connected, but tables do not exist yet. Run: python manage.py seed --drop")
    db.close()
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["check-db", "init-db", "seed", "export-sql", "run"])
    ap.add_argument("--drop", action="store_true", help="drop and recreate the database first")
    ap.add_argument("--no-demo", action="store_true", help="seed reference data only, no demo requests")
    args = ap.parse_args()
    app = create_app()
    if args.command == "check-db":
        return check_db(app)
    if args.command == "init-db":
        database.init_schema(app, drop_existing=args.drop)
        print("Schema created.")
    elif args.command == "seed":
        import seed
        seed.run(app, drop=args.drop, with_demo=not args.no_demo)
        print("Database seeded. Demo password for every account: %s" % seed.DEMO_PASSWORD)
    elif args.command == "export-sql":
        export_sql(app, os.path.join(os.path.dirname(os.path.abspath(__file__)), "sql", "sample_data.sql"))
    else:
        app.run(host=os.environ.get("HOST", "127.0.0.1"), port=int(os.environ.get("PORT", "5000")))


if __name__ == "__main__":
    sys.exit(main())